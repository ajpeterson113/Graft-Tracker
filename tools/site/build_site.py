def stock_row(s_, L, tr):
    """One size like the app's stock row: size, on hand against the target, status, then use, timing and expiry."""
    oasis = str(s_.get('product', '')).startswith('OASIS')
    oh = num(s_.get('onHand'))
    mn, mx = num(s_.get('min')), num(s_.get('max'))
    low = mn is not None and oh is not None and oh < mn
    per_box = num(s_.get('perBox')) if oasis else None
    size = f"**{T(s_.get('size'))}**<br>{nb(T(str(s_.get('product', '')).replace('OASIS ', 'OASIS ')))}"
    onh = (('🟠 ' if low else '') + f"**{fnum(oh) if oh is not None else '—'}**" + ((' sheet' if oh == 1 else ' sheets') if oasis else ''))
    if mn is not None and mx is not None:
        onh += '<br>' + nb('target ' + (f'{fnum(mn)}\u2060–\u2060{fnum(mx)}' if mn != mx else fnum(mn)))
    st = str(s_.get('status') or '')
    order = num(s_.get('order'))
    if re.search('reorder|order soon', st, re.I):
        tag = '🟠 ' + T(st) + (f" · order {fnum(order)}" + (' box' + ('es' if order > 1 else '') if oasis else '') if order else '')
    elif num(s_.get('expBeforeUse')):
        tag = f"🔴 {fnum(s_['expBeforeUse'])} expire before use"
    elif re.search('no patients', st, re.I):
        tag = T(st)
    elif re.match(r'^ok$', st, re.I):
        tag = '🟢 OK'
    else:
        tag = T(st) if st else ''
    meta = []
    use = num(s_.get('usePerWeek'))
    if use:
        meta.append(f'{fnum(use)}/wk')
    if num(s_.get('weeksLeft')) is not None and use:
        meta.append(f"{num(s_['weeksLeft']):.1f} wks left")
    if per_box:
        meta.append(f'box of {fnum(per_box)}')
    if okd(s_.get('runsOut')) and use:
        meta.append('out week of ' + md(s_['runsOut']))
    if num(s_.get('covers')) is not None:
        end = (tr.snap.get('period') or {}).get('end')
        meta.append(f"{fnum(s_['covers'])} projected use through {md(end)}" if okd(end) else f"covers {fnum(s_['covers'])}")
    if num(s_.get('incoming')):
        meta.append(f"+{fnum(s_['incoming'])} incoming")
    if okd(s_.get('nextExp')):
        meta.append('next exp ' + mdy(s_['nextExp']))
    if s_.get('po'):
        meta.append(str(s_['po']))
    det = T(' · '.join(meta))
    note = first_sent(s_.get('note'), 160) if s_.get('note') else ''
    if note:
        det += ('<br>' if det else '') + f'<sub>{T(note)}</sub>'
    return [size, onh, tag or '—', det]


