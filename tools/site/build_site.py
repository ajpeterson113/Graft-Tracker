def stamp_iso(s):
    try:
        dt = datetime.fromisoformat(str(s))
        if CHI and dt.tzinfo:
            dt = dt.astimezone(CHI)
        return stamp(dt)
    except Exception:
        return str(s or '')


def case_row(tr, c, page, show_date=True):
    """One case like the app's case row: who and where, then graft · PO · lot/SN; amount; status pill; notes."""
    flags = c.get('flags') or []
    link = tr.sheet_link(c, page)
    where = ' · '.join(x for x in [c.get('short'), short_dr(c.get('surgeon'))] if x)
    if c.get('ini'):
        who_ = f"**{T(c['ini'])}**"
        if link:
            who_ = f"[{who_}]({link}) 📄"
        line1 = who_ + ' · ' + T(where)
        line2 = [pdesc(c)]
    else:
        line1 = f"**{T(pdesc(c))}** · {T(where)}"
        line2 = []
    line2.append(('PO ' + c['po']) if c.get('po') else 'no PO yet')
    lots = ', '.join(c.get('lots') or [])
    if lots:
        line2.append(lots + (f" ({c['lotNote']})" if c.get('lotNote') else ''))
    elif c.get('lotNote'):
        line2.append(c['lotNote'])
    fl = []
    if 'billing' in flags:
        fl.append('⚠️&nbsp;Billing')
    if 'transfer' in flags:
        fl.append('🔁&nbsp;Transfer')
    if 'nolot' in flags:
        fl.append('⏳&nbsp;Lot/SN&nbsp;to&nbsp;come')
    status = f"{ST_DOT[c['status']]}&nbsp;{nb(ST[c['status']][1])}" + ('<br>' + '<br>'.join(fl) if fl else '')
    notes = c.get('notes') or ''
    case = line1 + '<br>' + T(' · '.join(line2))
    if notes:
        case += f'<details><summary><sub>Notes</sub></summary>{T(notes)}</details>'
    return [f"**{T(md(c['date']))}**" if show_date else '',
            case,
            T(m2(c.get('price'))) if c.get('price') is not None else 'No&nbsp;sale',
            status]


def cases_table(tr, cases, page):
    rows, last = [], None
    for c in sorted(cases, key=lambda c: (c['date'] or '', -ST_ORDER.index(c['status'])), reverse=True):
        rows.append(case_row(tr, c, page, c['date'] != last))
        last = c['date']
    return table(['Date', 'Case', 'Amount', 'Status'], rows, ['l', 'l', 'r', 'l'])


