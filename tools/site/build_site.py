def one_sheet(s):
    """'1 sheets' -> '1 sheet' in counts that come from the tracker's stock alerts."""
    return re.sub(r'(?<![\d.,])1 sheets\b', '1 sheet', s) if isinstance(s, str) else s


def alert_boxes(alerts, tail=None):
    """Stock alerts as GitHub callouts: one red box for problems, one amber box for reorders."""
    out = []
    for level, kind in (('bad', 'CAUTION'), ('warn', 'WARNING')):
        its = [a for a in alerts if (a.get('level') == 'bad') == (level == 'bad')]
        if not its:
            continue
        lines = [f"> [!{kind}]"]
        for a in its:
            title, text = one_sheet(a.get('title')), one_sheet(a.get('text'))
            lines.append(f"> - **{T(title)}**" + (f" · {T(text)}" if text else '') + (tail(a) if tail else ''))
        out.append('\n'.join(lines) + '\n')
    return '\n'.join(out)


def item_desc(i):
    pr = ' '.join(x for x in [i.get('product'), i.get('size')] if x)
    g = i.get('g')
    if g in ('patients', 'newstart'):
        if not num(i.get('up')) and not num(i.get('down')):
            return first_sent(i.get('note')) or ' · '.join(x for x in [pr, i.get('freq')] if x)
        units = num(i.get('units'))
        vis = num(i.get('visits'))
        s = ' · '.join(x for x in [
            ((f"{int(units)}× " if units and units > 1 and not re.search(r'[+×]', i.get('size') or '') else '') + (i.get('size') or 'size TBD')),
            i.get('freq'), (f"{int(vis)} visit{'' if vis == 1 else 's'}" if vis is not None else ''),
            ('from ' + md(i['start'])) if okd(i.get('start')) and i['start'] > TODAY else ''] if x)
        dv = num(i.get('downVisits'))
        if (i.get('downSize') and i.get('downSize') != i.get('size') and i.get('downSize') != '0') or (dv is not None and dv != vis):
            s += f" → {i.get('downSize') if i.get('downSize') not in (None, '', '0') else i.get('size')}" + \
                 (f" ×{int(dv)}" if dv is not None and dv != vis else '')
        return s
    if g == 'wcc':
        return f"{pr} · {int(num(i.get('inStock')) or 0)} on the shelf cover {int(num(i.get('unitsUp')) or 0)} projected" + \
               (f" · {i['po']}" if i.get('po') else '')
    if g == 'stravix':
        return ' · '.join(x for x in [pr, dshort(i['date']) if okd(i.get('date')) else '',
                                      i.get('ini') if i.get('ini') and not re.search('restock', i.get('ini'), re.I) else ''] if x)
    if g == 'oasis':
        bu = int(num(i.get('boxesUp')) or 0)
        return f"{pr} · {bu} up / {int(num(i.get('boxesDown')) or 0)} down box{'' if bu == 1 else 'es'}" + \
               (f" · {i['patients']}" if i.get('patients') else '')
    return pr


def item_who(i):
    g = i.get('g')
    if g == 'wcc':
        return 'WCC stock'
    if g == 'oasis':
        return i.get('surgeon') or 'OASIS'
    return ' · '.join(x for x in [i.get('ini'), i.get('surgeon')] if x)


