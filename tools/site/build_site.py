def sort_patients(rows):
    so = {k: i for i, (k, _) in enumerate(STATUS)}
    END = ['pending', 'denied', 'hold', 'done']

    def grp(p):
        return 1 if p.get('status') in END else 0

    def ak(p):
        nx = p.get('next') or ''
        return (nx + 'T' + (p.get('nextTime') or '99:99')) if nx and nx >= TODAY else '~'

    def or_key(p):
        """OR cases: newest case first, ones without a date last."""
        if p.get('status') != 'or':
            return (0, 0)
        cd = p.get('caseDate') or ''
        return (0, -D(cd).toordinal()) if okd(cd) else (1, 0)

    def key(p):
        acct = p.get('account') or ''
        ai = ACCTS.index(acct) if acct in ACCTS else 99
        g = grp(p)
        return (ai, g, END.index(p['status']) if g else 0, ak(p), so.get(p.get('status'), 9), or_key(p),
                p.get('provider') or '', num(p.get('order')) or 0)
    return sorted(rows, key=key)


def when_line(p, pt):
    if p.get('status') == 'or':
        if okd(p.get('caseDate')):
            return f"OR {dshort(p['caseDate'])} · {postop(p['caseDate'])}"
        return ('OR ' + md(p['last'])) if p.get('last') else ''
    if p.get('next'):
        nx = p['next']
        return (f"{'Was due' if nx < TODAY else 'Next'} {dshort(nx)}" + (f" {ftime(p['nextTime'])}" if p.get('nextTime') else '') +
                (f" · {p['nextLoc']}" if p.get('nextLoc') else '') + (f" · {p['cover']} covering" if p.get('cover') and nx >= TODAY else ''))
    if p.get('last'):
        return 'Last graft ' + md(p['last'])
    return ''


