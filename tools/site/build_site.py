# ================================================================ Targets page: tab bar only
def refresh_prospects(repo, counts):
    p = Path(repo) / 'Prospects.md'
    if not p.exists():
        return None
    txt = p.read_text()
    bar = '<!-- tabs:start -->\n' + tabbar('Prospects.md', 'targets', counts) + '<!-- tabs:end -->\n'
    if '<!-- tabs:start -->' in txt and '<!-- tabs:end -->' in txt:
        txt = re.sub(r'<!-- tabs:start -->.*?<!-- tabs:end -->\n?', bar.replace('\\', '\\\\'), txt, count=1, flags=re.S)
    else:
        txt = re.sub(r'^\[← Graft Tracker\]\(README\.md\) · \[Patients\]\(Patients\.md\)\s*\n', '', txt, count=1, flags=re.M)
        lines = txt.split('\n')
        i = next((k for k, l in enumerate(lines) if l.startswith('# ')), -1)
        lines.insert(i + 1, '\n' + bar.rstrip('\n'))
        txt = '\n'.join(lines)
    p.write_text(txt)
    return 'Prospects.md'


