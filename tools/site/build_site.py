def first_sent(s, mx=170):
    """First sentence of a note (the apps' firstSent)."""
    s = str(s or '').strip()
    for m in re.finditer(r'\.(\s+|$)', s):
        pre = s[:m.start()]
        last = re.search(r'(\S+)$', pre)
        tok = re.sub(r'^[(\["\'…]+', '', last.group(1) if last else '')
        if re.match(r'^(Dr|St|Mr|Ms|Mrs|vs|No|approx|incl|Wk|wk)$', tok, re.I) or re.match(r'^([A-Z]\.)*[A-Z]$', tok) \
                or re.match(r'^\d+$', tok):
            continue
        if m.start() < 12:
            continue
        out = s[:m.start() + 1]
        return out if len(out) <= mx else out[:mx - 1] + '…'
    return s if len(s) <= mx else s[:mx - 1] + '…'


def short_dr(s):
    return re.sub(r'^Dr\.?\s*', '', str(s or '')).strip()


def grafix_label(s):
    return re.sub(r'\bgrafix(?:\s*pl)?(?:\s*prime)?(?:\s*pl)?\b®?', 'GRAFIX', str(s or ''), flags=re.I)


def load_json(p, default=None):
    try:
        with open(p) as f:
            return json.load(f)
    except Exception:
        return default


def load_dir(d):
    out = []
    for f in sorted(glob.glob(os.path.join(d, '*.json'))):
        x = load_json(f)
        if isinstance(x, dict):
            x.setdefault('id', os.path.basename(f)[:-5])
            out.append(x)
    return out


def write(repo, rel, text):
    p = Path(repo) / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text.rstrip() + '\n')
    return rel


def rel(from_page, target):
    """Relative link from one page of the site to a repo path."""
    depth = from_page.count('/')
    return '../' * depth + target


