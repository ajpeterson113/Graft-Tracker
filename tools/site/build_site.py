def day_section(pt, d, key, page, label_today=True):
    vs = pt.visits_for(d)
    logged = len([v for v in vs if v['e']])
    title = dlong(d) + (' · Today' if d == TODAY and label_today else '')
    out = [anchor(key) + f'### {T(title)}\n']
    # grafts needed and coverage
    need, cov = {}, {}
    for v in vs:
        if v['cover'] and not v['e']:
            cov[v['cover']] = cov.get(v['cover'], 0) + 1
        if v['e']:
            continue
        raw = prod_of(v['p'])
        k = strip_qty(raw)
        if k:
            need[k] = need.get(k, 0) + qty_of(raw)
    bits = [f"{len(vs)} visit{'' if len(vs) == 1 else 's'}" + (f' · {logged} logged' if logged else '')]
    if need:
        bits.append('**Grafts:** ' + ' · '.join(T(k) + (f' ×{n}' if n > 1 else '') for k, n in sorted(need.items(), key=lambda kv: (-kv[1], kv[0]))))
    if cov:
        bits.append('**Covering:** ' + ' · '.join(f'{T(k)} {n}' for k, n in sorted(cov.items())))
    out.append(' · '.join(bits) + '\n')
    if not vs:
        out.append(f'No visits booked for {T(dshort(d))}.\n')
    else:
        def tk(v):
            return v['time'] or '99:99'
        ai = {a: i for i, a in enumerate(ACCTS)}
        rows = sorted(vs, key=lambda v: (tk(v), ai.get(v['p'].get('account'), 99), v['p'].get('provider') or '', ini(v['p'])))
        out.append(table(['Time', 'Patient', 'Visit', 'Clinic', 'Status'], [visit_cells(pt, v, d, page) for v in rows]))
    if d >= pt.cws:
        miss = pt.miss_for(d, vs)
        if miss:
            miss.sort(key=lambda p: (ACCTS.index(p['account']) if p.get('account') in ACCTS else 99, p.get('provider') or ''))
            out.append(f"\n🔴 **No follow-up · usually seen {DAYN[D(d).weekday()]}s** · {len(miss)}\n\n")
            out.append(table(['Patient', 'Clinic', 'Graft', 'Surgeon', 'Why'],
                             [[who(p), T(SHORT.get(p.get('account'), p.get('account'))), T(prod_of(p)), T(short_dr(p.get('provider'))),
                               T(pt.fu_reason(p))] for p in miss]))
    return '\n'.join(out)


def qty_of(s):
    s = str(s or '')
    m = re.search(r'\b(\d+)\s*(?:sheets?|pcs?|pieces?|discs?)\b', s, re.I) or re.search(r'\(\s*[x×]\s*(\d+)\s*\)', s, re.I) or \
        re.search(r'\(\s*(\d+)\s*\)', s)
    return max(1, int(m.group(1))) if m else 1


def strip_qty(s):
    s = str(s or '')
    s = re.sub(r'\s*\(?\s*\b\d+\s*(?:sheets?|pcs?|pieces?|discs?)\b\s*\)?', '', s, count=1, flags=re.I)
    s = re.sub(r'\s*\(\s*[x×]?\s*\d+\s*\)', '', s, count=1, flags=re.I)
    s = re.sub(r'\s*\((?:suggested|est\.?|estimated)\)', '', s, flags=re.I)
    return re.sub(r'\s{2,}', ' ', s).strip()


def page_patients_week(pt, counts, sub):
    page = 'patients/week.md'
    out = [patient_header(page, 'This week', pt, counts, sub, 'week')]
    ws = pt.cws
    days = week_days(ws)
    a, b = D(days[0]), D(days[4])
    lab = 'This week' if ws <= TODAY else 'Next week'
    out.append(f"\n**{lab} · {MON[a.month - 1]} {a.day}–{'' if a.month == b.month else MON[b.month - 1] + ' '}{b.day}** · "
               f"🟠 to verify · 🔴 no follow-up booked\n")
    heads, cells = [], []
    for i, d in enumerate(days):
        vs = pt.visits_for(d)
        miss = len(pt.miss_for(d, vs))
        vn = len([v for v in vs if not v['e'] and pt.vfy(v['p'])])
        heads.append(f"[{DAYN[D(d).weekday()][:3]} {D(d).day}{' · today' if d == TODAY else ''}](#{DAY_KEYS[i]})")
        cells.append(f"**{len(vs)}**{' 🟠' if vn else ''}{' 🔴' if miss else ''}")
    out.append(table(heads, [cells], ['c'] * 5))
    for i, d in enumerate(days):
        out.append('\n' + day_section(pt, d, DAY_KEYS[i], page))
    # week at a glance
    per = [pt.visits_for(d) for d in days]
    allv = [v for vs in per for v in vs]
    if allv:
        A, S, cov = {}, {}, {}
        for i, vs in enumerate(per):
            for v in vs:
                acc = v['p'].get('account') or 'Other'
                r = A.setdefault(acc, {'n': 0, 'd': [0] * 5, 's': {}})
                r['n'] += 1
                r['d'][i] += 1
                if not (v['e'] and not v['e'].get('grafted')):
                    raw = (v['e'].get('size') if v['e'] and v['e'].get('size') else prod_of(v['p']))
                    if v['e'] and v['e'].get('size') and not re.search('grafix|oasis|stravix', raw, re.I):
                        raw = ' '.join(x for x in [v['p'].get('product'), raw] if x)
                    k = grafix_label(strip_qty(raw))
                    if k:
                        r['s'][k] = r['s'].get(k, 0) + qty_of(raw)
                        S[k] = S.get(k, 0) + qty_of(raw)
                if v['cover'] and not v['e']:
                    cov[v['cover']] = cov.get(v['cover'], 0) + 1
        rows = []
        for acc in [x for x in ACCTS if x in A] + [x for x in A if x not in ACCTS]:
            r = A[acc]
            rows.append([f"**{T(SHORT.get(acc, acc))}**"] + [str(n) if n else '–' for n in r['d']] + [str(r['n']),
                        T(' · '.join(f'{k} ×{n}' for k, n in sorted(r['s'].items(), key=lambda kv: (-kv[1], kv[0]))))])
        rows.append(['**All clinics**'] + [f'**{len(vs)}**' for vs in per] + [f'**{len(allv)}**',
                    T(' · '.join(f'{k} ×{n}' for k, n in sorted(S.items(), key=lambda kv: (-kv[1], kv[0]))))])
        out.append(anchor('glance') + '\n### Week at a glance\n')
        out.append(table(['Clinic'] + [f"{DAYN[D(d).weekday()][:3]} {md(d)}" for d in days] + ['Visits', 'Grafts'], rows,
                         ['l', 'c', 'c', 'c', 'c', 'c', 'c', 'l']))
        if cov:
            out.append('\n**Covering this week:** ' + ' · '.join(f'{T(k)} {n}' for k, n in sorted(cov.items())) + '\n')
    # next week, if anything is booked
    nws = addd(ws, 7)
    ndays = week_days(nws)
    if any(pt.visits_for(d) for d in ndays):
        body = '\n'.join(day_section(pt, d, 'next-' + DAY_KEYS[i], page, False) for i, d in enumerate(ndays) if pt.visits_for(d))
        n = sum(len(pt.visits_for(d)) for d in ndays)
        out.append('\n' + details(f'<b>Next week</b> · {n} visit{"" if n == 1 else "s"} booked so far', body))
    return page, '\n'.join(out)


def page_patients_todo(pt, counts, sub):
    page = 'patients/todo.md'
    out = [patient_header(page, 'Patient to-do', pt, counts, sub, 'todo')]
    ai = {a: i for i, a in enumerate(ACCTS)}

    def ordk(p):
        return (ai.get(p.get('account'), 99), p.get('provider') or '', p.get('initials') or '')
    V = sorted([p for p in pt.pts if pt.vfy(p)], key=ordk)
    N = sorted([p for p in pt.pts if pt.no_fu(p)], key=ordk)
    NS = sorted([p for p in pt.pts if p.get('status') == 'approved'], key=ordk)
    PE = sorted([p for p in pt.pts if p.get('status') == 'pending'], key=lambda p: (0 if pt.ivr_due(p) else 1,) + ordk(p))
