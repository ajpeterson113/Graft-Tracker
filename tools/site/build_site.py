def render_home_image(tr, path, theme, narrow=False):
    """The Graft Tracker app's period card and weekly sales, side by side (wide) or stacked (narrow, for phones)."""
    from PIL import Image, ImageChops, ImageDraw, ImageFont
    C = PAL[theme]
    S = 2
    fcache = {}

    def F(name, size):
        k = (name, size)
        if k not in fcache:
            fcache[k] = ImageFont.truetype(str(FONTS / f'{name}.ttf'), int(round(size * S)))
        return fcache[k]

    snap = tr.snap
    Sa, Fo, P = snap.get('sales') or {}, snap.get('forecast') or {}, snap.get('period') or {}
    si = tr.ship()
    tgt = num(Sa.get('target')) or num(Fo.get('target')) or 0
    sold = num(Sa.get('total')) or 0
    up = num(Fo.get('up')) or sold
    down = num(Fo.get('down')) or sold
    # headline = in SFDC + submitted (what SFDC should show once it posts); booked total is secondary (same as the app)
    pcs0 = tr.period_cases()
    in_sfdc = sum(num(c.get('price')) or 0 for c in pcs0 if c.get('status') == 'insfdc')
    f4, f6 = F('SourceSans3-400', 13.5), F('SourceSans3-600', 13.5)
    sub_w = (f4.getlength('In SFDC + submitted') + f6.getlength(m0(in_sfdc)) + f4.getlength(' in SFDC · ')
             + f6.getlength(m0(sold)) + f4.getlength(' booked')) / S + 21
    sub_wrap = 20 + sub_w > (420 if narrow else 548) - 20  # card padding is 20
    in_sub = min(sold, sum(num(c.get('price')) or 0 for c in pcs0 if c.get('status') in ('insfdc', 'submitted')))
    not_sub = max(0, sold - in_sub)
    PAD, GAP = 20, 16
    if narrow:
        W = W1 = W2 = 420
    else:
        W1, W2 = 548, 316
        W = W1 + GAP + W2
    lo, hi = num(P.get('rateMiss')) or .07, num(P.get('rateHit')) or .1
    gap_txt = ''
    if tgt and down < tgt:
        gap_txt = (f'Hitting target pays {rnd(hi * 100)}% on everything. Closing the {m0(tgt - down)} downside gap '
                   f'adds about {m0(tgt * hi - down * lo)} in commission.')

    def wrap(text_, font, width):
        lines, cur = [], ''
        for w in text_.split(' '):
            t = (cur + ' ' + w).strip()
            if font.getlength(t) <= width * S or not cur:
                cur = t
            else:
                lines.append(cur)
                cur = w
        if cur:
            lines.append(cur)
        return lines

    f_gap = F('SourceSans3-400', 13.5)
    gap_lines = wrap(gap_txt, f_gap, W1 - 2 * PAD - 20) if gap_txt else []
    pace_parts = None  # filled below; narrow layout wraps the pace line
    # legend items, wrapped onto a second line when the card is narrow
    fl13, fb13 = F('SourceSans3-400', 13.5), F('SourceSans3-700', 13.5)
    legend = ([('sold', 'Submitted', mk(in_sub), '')] + ([('po', 'Not submitted', mk(not_sub), '')] if not_sub > 0 else [])
              + [('down', 'Downside', mk(down), pc(Fo.get('pctDown'))), ('up', 'Upside', mk(up), pc(Fo.get('pctUp')))])

    def leg_w(it):
        _, lab, val, extra = it
        return 15 + (fl13.getlength(lab + ' ') + fb13.getlength(val) + (fl13.getlength(' ' + extra) if extra else 0)) / S
    leg_lines, cur, cw = [], [], 0
    for it in legend:
        w_ = leg_w(it)
        if cur and PAD + cw + w_ > W1 - PAD:
            leg_lines.append(cur)
            cur, cw = [], 0
        cur.append(it)
        cw += w_ + 14
    leg_lines.append(cur)
    H1 = 300 + 30 + (20 if sub_wrap else 0) + (14 + 18 * len(gap_lines) + 18 if gap_lines else 0) + (20 if narrow else 0) + 19 * (len(leg_lines) - 1)
    H2 = 300 if not narrow else 250
