class Patients:
    def __init__(self, pdb, repo):
        d = pdb
        if os.path.isdir(os.path.join(pdb, 'patients')):
            d = os.path.join(pdb, 'patients')
            self.inbox = [x for x in load_dir(os.path.join(pdb, 'inbox')) if x.get('status') == 'new']
            self.csq = [x for x in load_dir(os.path.join(pdb, 'uploads')) if x.get('status') == 'new']
        else:
            self.inbox, self.csq = [], []
        self.pts = load_dir(d)
        self.repo = repo
        self.cws = ws_of(TODAY)

    # -- rules (same as the app)
    def fu_end(self):
        w = wd_js(TODAY)
        return addd(TODAY, (0 if w == 0 else 7 - w) + 7)

    @staticmethod
    def biwk(p):
        return bool(re.search(r'2|two|bi', (p.get('freq') or '').lower()))

    def fu_reason(self, p):
        st = p.get('status')
        if p.get('fuVerify') and st not in ('done', 'denied'):
            return 'Verify: ' + p['fuVerify']
        if st not in ('active', 'approved'):
            return ''
        nx = p.get('next') or ''
        if not nx:
            return 'No follow-up booked' + (f" (last graft {md(p['last'])})" if p.get('last') else '')
        if nx < TODAY:
            return f'Last appt {md(nx)} passed, nothing new booked'
        if not p.get('nextTime'):
            return f'Next {md(nx)}, no time'
        if nx > self.fu_end() and not self.biwk(p):
            return f'Next {md(nx)}, nothing booked next week'
        return ''

    def no_fu(self, p):
        return bool(self.fu_reason(p))

    @staticmethod
    def vfy(p):
        return p.get('verify') if p.get('verify') and p.get('status') not in ('done', 'denied') else ''

    def usual_day(self, p):
        own = [x for x in [e.get('date') for e in (p.get('log') or [])] + [p.get('last'),
               p.get('next') if p.get('next') and p.get('next') < TODAY else ''] if x and okd(x) and wd_js(x) % 6 != 0]
        pool = own
        if not pool:
            pool = [x for q in self.pts if q is not p and q.get('account') == p.get('account') and q.get('provider') == p.get('provider')
                    for x in (q.get('next'), q.get('last')) if x and okd(x) and wd_js(x) % 6 != 0]
        if not pool:
            return None
        cnt = {}
        for x in pool:
            cnt[wd_js(x)] = cnt.get(wd_js(x), 0) + 1
        latest = wd_js(sorted(pool)[-1])
        best, bn = None, 0
        for w in sorted(cnt):
            n = cnt[w]
            if n > bn or (n == bn and w == latest):
                best, bn = w, n
        return best

    def visits_for(self, day):
        out = []
        for p in self.pts:
            le = [e for e in (p.get('log') or []) if e.get('date') == day]
            if le:
                e = le[-1]
                sched = p.get('next') == day
                out.append({'p': p, 'e': e, 'time': e.get('time') or (p.get('nextTime') if sched else '') or '',
                            'loc': e.get('loc') or (p.get('nextLoc') if sched else '') or '', 'cover': e.get('cover') or '', 'kind': 'log'})
                continue
            if p.get('next') == day:
                out.append({'p': p, 'e': None, 'time': p.get('nextTime') or '', 'loc': p.get('nextLoc') or '',
                            'cover': p.get('cover') or '', 'kind': 'next'})
                continue
            if p.get('status') == 'or' and p.get('caseDate') == day:
                out.append({'p': p, 'e': None, 'time': '', 'loc': '', 'cover': p.get('cover') or '', 'kind': 'or'})
        return out

    def miss_for(self, day, vs):
        w = wd_js(day)
        seen = {id(v['p']) for v in vs}
        return [p for p in self.pts if id(p) not in seen and self.no_fu(p) and p.get('next') != day and self.usual_day(p) == w]

    @staticmethod
    def ivr_base(p):
        ds = sorted(x for x in [p.get('ivrDate'), p.get('ivrFu')] if okd(x))
        return ds[-1] if ds else (p.get('created') if okd(p.get('created')) else '')

    def ivr_due(self, p):
        b = self.ivr_base(p)
        return p.get('status') == 'pending' and b and (D(TODAY) - D(b)).days > 7

    def ivr_age(self, p):
        b = self.ivr_base(p)
        if not b:
            return 'No IVR date'
        n = (D(TODAY) - D(b)).days
        ago = 'today' if n == 0 else ('yesterday' if n == 1 else f'{n} days ago')
        fu = okd(p.get('ivrFu')) and p.get('ivrFu') >= (p.get('ivrDate') or '')
        return (f"Followed up {md(p['ivrFu'])}" if fu else (f"IVR sent {md(p['ivrDate'])}" if p.get('ivrDate')
                                                            else f"Added {md(p.get('created'))}")) + f' · {ago}'

    @staticmethod
    def pa_left(p):
        if okd(p.get('paExp')) and p.get('status') not in ('done', 'denied'):
            return (D(p['paExp']) - D(TODAY)).days
        return None

    def todo_count(self):
        s = {p['id'] for p in self.pts if self.vfy(p) or self.no_fu(p) or self.ivr_due(p) or
             (self.pa_left(p) is not None and self.pa_left(p) <= 30)}
        return len(s) + len(self.inbox) + len(self.csq)

    def ivr_link(self, p, page):
        if (Path(self.repo) / 'ivr' / f"{p['id']}.md").exists():
            return f"[📄 IVR]({rel(page, 'ivr/' + p['id'] + '.md')})"
        return ''


