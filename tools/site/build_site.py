# ================================================================ TRACKER DATA (Graft Tracker app docs)
class Tracker:
    def __init__(self, app_dir, repo, xlsx):
        self.snap = load_json(os.path.join(app_dir, 'meta', 'snap.json'), {}) or {}
        self.fc = load_json(os.path.join(app_dir, 'meta', 'forecast.json'), {}) or {}
        self.stk = load_json(os.path.join(app_dir, 'meta', 'stock.json'), {}) or {}
        self.months = {}
        for f in sorted(glob.glob(os.path.join(app_dir, 'months', '*.json'))):
            m = load_json(f)
            if m and m.get('cases') is not None:
                self.months[m.get('ym') or os.path.basename(f)[:-5]] = m
        self.cases = []
        for ym in sorted(self.months):
            M = self.months[ym]
            for c in M.get('cases') or []:
                c = dict(c)
                c['ym'], c['tab'], c['period'] = ym, M.get('tab'), M.get('period')
                if c.get('status') not in ST:
                    c['status'] = 'check'
                self.cases.append(c)
        self.repo = repo
        self.transfers = read_transfers(xlsx)
        P = self.snap.get('period') or {}
        self.cur_ym = P.get('ym') or (max(self.months) if self.months else '')

    # -- app logic
    def period_cases(self):
        return [c for c in self.cases if c['ym'] == self.cur_ym]

    def ship(self):
        P = self.snap.get('period') or {}
        cal = next((p for p in (P.get('calendar') or []) if p and p[0] == P.get('id')),
                   [P.get('id'), P.get('start'), P.get('end'), None])
        hol = set(P.get('holidays') or [])
        total = done = 0
        if okd(cal[1]) and okd(cal[2]):
            d = D(cal[1])
            while d <= D(cal[2]):
                s = d.isoformat()
                if d.weekday() < 5 and s not in hol:
                    total += 1
                    if s < TODAY:
                        done += 1
                d += timedelta(days=1)
        if cal[3]:
            total = int(cal[3])
        done = min(done, total)
        return {'id': cal[0], 'done': done, 'total': total, 'pct': done / total if total else 0,
                'ended': bool(cal[2]) and TODAY > str(cal[2]), 'start': cal[1], 'end': cal[2]}

    def alerts(self):
        out = []
        for L in self.stk.get('locations') or []:
            for a in L.get('alerts') or []:
                out.append(dict(a, loc=L.get('key'), locName=L.get('name')))
        return out

    def needs_look(self):
        return [c for c in self.cases if (c['status'] != 'insfdc' and any(f in ('billing', 'uncertain', 'pono')
                                                                            for f in c.get('flags') or [])) or c['status'] == 'check']

    def sheets_to_come(self):
        return [c for c in self.period_cases() if 'nolot' in (c.get('flags') or []) and c['status'] != 'stock']

    def todo_count(self):
        ids = {c['id'] for c in self.cases if c['status'] in ('ready', 'needspo') or
               ('billing' in (c.get('flags') or []) and c['status'] != 'insfdc')}
        ids |= {c['id'] for c in self.needs_look()}
        return len(ids)

    def sheet_link(self, c, page):
        slug = c.get('slug')
        if slug and (Path(self.repo) / 'case-sheets' / f'{slug}.md').exists():
            return rel(page, f'case-sheets/{slug}.md')
        return ''


def read_transfers(xlsx):
    rows = []
    try:
        import openpyxl
        wb = openpyxl.load_workbook(xlsx, data_only=True, read_only=True)
        if 'Transfers' not in wb.sheetnames:
            return rows
        ws = wb['Transfers']
        hdr = None
        for r in ws.iter_rows(values_only=True):
            vals = list(r)
            if hdr is None:
                if vals and vals[0] == 'Date' and 'Patient' in vals:
                    hdr = [str(v or '').strip() for v in vals]
                continue
            if not any(v not in (None, '') for v in vals):
                continue
            d = dict(zip(hdr, vals))
            if not d.get('Date'):
                continue
            rows.append(d)
    except Exception:
        return rows
    return rows


def pdesc(c):
    s = str(c.get('sz') or '')
    s = re.sub(r'\s*\(x(\d+)\)', r' ×\1', s)
    s = re.sub(r'\s*\(((?:\d+ sheets = 1 box)|(?:1 box of \d+))\)', r' · \1', s)
    multi = '×' in s
    return ' '.join(x for x in [c.get('prod'), s] if x) + ('' if multi or (num(c.get('qty')) or 0) <= 1 else f" ×{int(c['qty'])}")


def po_short(p):
    p = str(p or '')
    return '…' + p[-6:] if re.fullmatch(r'\d{12,}', p) else p


def case_title(c):
    return c.get('ini') or pdesc(c)


