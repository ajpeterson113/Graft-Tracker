INSURANCE_MONEY = re.compile(r'\s*(?:deductible|copay|co-pay|coinsurance|out[- ]of[- ]pocket)', re.I)


def scrub_money(s):
    """The patient pages carry no sales numbers: drop dollar amounts (a deductible or copay stays)."""
    s = str(s or '')

    def paren(m):
        return m.group(0) if INSURANCE_MONEY.search(m.group(0)) else ''
    s = re.sub(r'\s*\([^()]*\$\s?\d[^()]*\)', paren, s)

    def money(m):
        return m.group(0) if INSURANCE_MONEY.match(s, m.end()) else ''
    s = re.sub(r',?\s*\$\s?\d[\d,]*(?:\.\d+)?(?:\s*(?:each|per [a-z0-9²]+|/cm2|/cm²))?', money, s)
    s = re.sub(r'\s+([,.;)])', r'\1', s)
    s = re.sub(r'\(\s*\)', '', s)
    return re.sub(r'\s{2,}', ' ', s).strip()


def clean_notes(p):
    n = str(p.get('notes') or '').strip()
    n = re.sub(r'^⚠ Verify:.*?\|\s*', '', n) if n.startswith('⚠ Verify:') and '|' in n else n
    if n.startswith('⚠ Verify:') and '|' not in n:
        n = ''
    if not n and p.get('status') == 'pending' and okd(p.get('created')):
        n = 'New ' + md(p['created'])
    return scrub_money(n)


